'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {startTestDatabase}=require('./helpers/postgres');
const {createHttpApp}=require('../server/http/app');

test('administrator password setup, reset, isolation and session revocation',async t=>{
 const {db,owner}=await startTestDatabase(t);
 const sent=new Map();let clock=Date.now();
 const app=createHttpApp({db,authSecret:'password-test-secret-'.repeat(3),now:()=>clock,sendCode:async(email,code)=>sent.set(email,code)});
 const identity=app.locals.identity;
 const admin=await identity.provision({email:'master@example.com',role:'admin'});
 const student=await identity.provision({email:'student@example.com'});
 const password='A strong test password 2026';
 await identity.requestCode(admin.email,'127.0.0.1');
 const oldSession=await identity.verifyCode(admin.email,sent.get(admin.email),'127.0.0.1');
 clock+=61000;
 await identity.requestCode(admin.email,'127.0.0.1','password_reset');
 const code=sent.get(admin.email);
 await assert.rejects(identity.verifyCode(admin.email,code,'127.0.0.1'),e=>e.code==='INVALID_CODE');
 await assert.rejects(identity.verifyCode(admin.email,code,'127.0.0.1','short'),e=>e.code==='INVALID_PASSWORD');
 const session=await identity.verifyCode(admin.email,code,'127.0.0.1',password);
 await assert.rejects(identity.authenticate(oldSession.token),e=>e.code==='UNAUTHENTICATED');
 assert.equal((await identity.authenticate(session.token)).user.role,'admin');
 await assert.rejects(identity.verifyCode(admin.email,code,'127.0.0.1',password),e=>e.code==='INVALID_CODE');
 await assert.rejects(identity.loginPassword(admin.email,'incorrect password','127.0.0.1'),e=>e.code==='INVALID_CREDENTIALS');
 assert.ok((await identity.loginPassword(admin.email,password,'127.0.0.1')).token);
 const stored=await owner.query('SELECT password_hash FROM up_private.admin_passwords WHERE user_id=$1',[admin.id]);
 assert.match(stored.rows[0].password_hash,/^scrypt-v1\$/);
 assert.ok(!stored.rows[0].password_hash.includes(password));
 clock+=901000;sent.clear();
 await identity.requestCode(admin.email,'127.0.0.1');
 assert.equal(sent.has(admin.email),false);
 await identity.requestCode(student.email,'127.0.0.2','password_reset');
 assert.equal(sent.has(student.email),false);
 clock+=61000;
 await identity.requestCode(student.email,'127.0.0.2');
 await assert.rejects(identity.verifyCode(student.email,sent.get(student.email),'127.0.0.2',password),e=>e.code==='INVALID_CODE');
 assert.ok((await identity.verifyCode(student.email,sent.get(student.email),'127.0.0.2')).token);
 await identity.requestCode(admin.email,'127.0.0.3','password_reset');
 await identity.verifyCode(admin.email,sent.get(admin.email),'127.0.0.3',password+' changed');
 await assert.rejects(identity.authenticate(session.token),e=>e.code==='UNAUTHENTICATED');
 await assert.rejects(identity.loginPassword(admin.email,password,'127.0.0.3'),e=>e.code==='INVALID_CREDENTIALS');
 assert.ok((await identity.loginPassword(admin.email,password+' changed','127.0.0.3')).token);
 const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));t.after(()=>new Promise(r=>server.close(r)));
 const base='http://127.0.0.1:'+server.address().port;
 const login=await fetch(base+'/api/v1/auth/password/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:admin.email,password:password+' changed'})});
 assert.equal(login.status,200);
 const cookie=login.headers.get('set-cookie');assert.match(cookie,/HttpOnly/i);assert.match(cookie,/SameSite=Strict/i);
 assert.equal((await fetch(base+'/app/student-preview.html',{headers:{Cookie:cookie.split(';')[0]}})).status,200);
 assert.equal((await fetch(base+'/app/student-preview.html')).status,401);
 for(let i=0;i<10;i++)await identity.loginPassword('missing@example.com',password,'127.0.0.4').catch(()=>{});
 await assert.rejects(identity.loginPassword('missing@example.com',password,'127.0.0.4'),e=>e.code==='RATE_LIMITED');
});
